// @ts-check
import starlight from "@astrojs/starlight";
import { defineConfig } from "astro/config";

/**
 * The tx402 documentation site.
 *
 * Every page is `.mdx` under `src/content/docs`. Two of them — `reference/errors.mdx` and
 * `reference/api-typescript.mdx` — are **generated** by `node tools/docs-gen/index.js
 * build` and must never be hand-edited: the error table is emitted from the SPEC §8
 * taxonomy and the SPEC §11 exit-code map in the shipped source, so a documented code and
 * a real one cannot drift. `pnpm docs:check` fails if they do.
 *
 * `site` matches `PROJECT_URLS.documentation` (https://docs.tx402.io) and there is
 * deliberately **no `base`**: the docs live at the root of their own subdomain, so every
 * emitted link is `/guides/…` rather than `/docs/guides/…`. Until S15b the site was served
 * from `tx402.dev/docs` and carried `base: "/docs"`; keeping that after the move would
 * produce `docs.tx402.io/docs/…`, a duplicated path segment in every URL.
 *
 * It is declared here rather than in a deploy script so a local preview has the same URLs
 * as production and a relative link cannot work in one and 404 in the other.
 */
export default defineConfig({
  site: "https://docs.tx402.io",
  trailingSlash: "ignore",
  integrations: [
    starlight({
      title: "tx402",
      description:
        "Resilient x402 buyer SDK — deterministic multi-chain payment routing, local spend guardrails, and a drop-in HTTP client for autonomous agents.",
      social: [
        {
          icon: "github",
          label: "GitHub",
          href: "https://github.com/neogeeks/tx402",
        },
      ],
      editLink: {
        baseUrl: "https://github.com/neogeeks/tx402/edit/main/docs/",
      },
      // Groups are autogenerated from the directory layout and ordered by each page's
      // `sidebar.order`, so adding a page is adding a file — there is no second list here
      // to forget to update.
      sidebar: [
        { label: "Start here", items: [{ autogenerate: { directory: "start" } }] },
        { label: "Guides", items: [{ autogenerate: { directory: "guides" } }] },
        { label: "Reference", items: [{ autogenerate: { directory: "reference" } }] },
        { label: "Security", items: [{ autogenerate: { directory: "security" } }] },
        { label: "Operations", items: [{ autogenerate: { directory: "operations" } }] },
      ],
      customCss: ["./src/styles/tx402.css"],
      lastUpdated: true,
    }),
  ],
});
